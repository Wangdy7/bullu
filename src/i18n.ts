const dictionary: Record<Exclude<Language, 'zh'>, TranslationMap> = { en, ms }

export function translate(
  language: Language,
  source: string,
  vars?: Record<string, string | number>,
) {
  if (language === 'zh') return interpolate(source, vars)
  const translated = dictionary[language][source] ?? source
  return interpolate(translated, vars)
}

function interpolate(source: string, vars?: Record<string, string | number>) {
  if (!vars) return source
  return source.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] === undefined ? `{${key}}` : String(vars[key]),
  )
}

export function addTranslations(language: Exclude<Language, 'zh'>, values: TranslationMap) {
  Object.assign(dictionary[language], values)
}


