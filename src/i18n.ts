/**
 * Translate an arbitrary rendered string. Exact dictionary entries are preferred;
 * then common short prefixes/suffixes and count-time patterns are handled.
 */
export function translateText(language: Language, source: string) {
  if (language === 'zh' || !/[\u3400-\u9fff]/.test(source)) return source
  const leading = source.match(/^\s*/)?.[0] ?? ''
  const trailing = source.match(/\s*$/)?.[0] ?? ''
  const core = source.trim()
  if (!core) return source

  const exact = dictionary[language][core]
  if (exact) return `${leading}${exact}${trailing}`

  return source
}


